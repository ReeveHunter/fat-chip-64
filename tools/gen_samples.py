#!/usr/bin/env python3
"""The sampler's sample table (v0.68) -> src/smptab.asm, under the I/O.

One byte per MidiNES sample, A0-A127 then B0-B127 (the index is the sample's
byte as the beats use it: bit 7 = bank B, bits 0-6 = its note):
  high nibble  its hit type, the letter the browser shows: K S H P L T F V
               (kick, snare, hats and cymbals, toms and percussion, layered,
               tonal, FX, vocal) - Reeve's Sound Sorter buckets (patch/clips.json)
  low nibble   its Game Boy partner: 1 + the beat lane whose Game Boy drum it
               plays (gbDrumNote's order), or 0 for none (tonal, FX, vocal and
               a few percussion FX play on the MidiNES only)
"""
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, "..")
CLIPS = json.load(open(os.path.join(ROOT, "patch", "clips.json")))["clips"]

TYPES = ["kick", "snare", "hats", "perc", "layer", "tonal", "fx", "vocal"]
LETTERS = "KSHPLTFV"
LANES = ["bd", "sd", "cp", "rm", "ht", "mt", "lt", "ch", "oh", "cy", "rd", "sh", "cb", "cl"]   # gbDrumNote's order
SUB_LANE = {"ctight": "ch", "cloose": "ch", "open": "oh", "o2c": "oh", "half": "oh", "crash": "cy", "ride": "rd",
            "tom": "mt", "clap": "cp", "rim": "rm", "cowbell": "cb", "clave": "cl", "tamb": "sh", "roto": "ht",
            "conga": "lt", "timbale": "ht",
            "khc": "bd", "kho": "bd", "ksn": "bd", "kcy": "bd", "shc": "sd", "sho": "sd", "scy": "sd"}


def lane(c):
    if c["bucket"] == "kick":
        return "bd"
    if c["bucket"] == "snare":
        return "sd"
    return SUB_LANE.get(c["sub"])


def main():
    out = []
    for bank in "AB":
        for n in range(128):
            c = CLIPS[f"{bank}{n}"]
            t = TYPES.index(c["bucket"])
            ln = lane(c)
            out.append(t << 4 | (LANES.index(ln) + 1 if ln else 0))
    lines = ["; Generated by tools/gen_samples.py - do not edit. (under the I/O: SmpTypeOf)",
             "; per sample A0-A127, B0-B127: type (K S H P L T F V) << 4 | Game Boy lane + 1 (0: none)",
             "smpType:"]
    for i in range(0, 256, 16):
        lines.append("\t.byte " + ",".join(f"${v:02X}" for v in out[i:i + 16]))
    open(os.path.join(ROOT, "src", "smptab.asm"), "w").write("\n".join(lines) + "\n")
    print("256 samples ->", os.path.join(ROOT, "src", "smptab.asm"), "letters", LETTERS)


if __name__ == "__main__":
    main()
