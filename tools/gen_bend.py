#!/usr/bin/env python3
"""Fat Chip 64 bend tables -> src/bendtab.asm (v0.13).

The bend everything gets is m = 0..192 sixteenths of a semitone (up to an
octave), up or down:
  SID       f x (1 - sidDn[m] / 65536) down, f x (1 + sidUp[m] / 65536) up
  MidiNES   the bend for triangle note n = p(n) x nesDn[m] / 8192 (down) or
            x nesUp[m] / 8192 (up); pulses twice that. p = triPb (1710 at
            MIDI 36). From the MidiNES bend maths (notes/midines.md):
            bend for x octaves = p (2 - 2 x 0.5^x)
  Game Boy  its bend range is set to 12, so the bend is m x 8192 / 192
"""
import os

OUT = os.path.join(os.path.dirname(__file__), "..", "src", "bendtab.asm")
N = 193


def tab(name, vals):
    lo = [v & 0xFF for v in vals]
    hi = [v >> 8 for v in vals]
    out = []
    for suffix, arr in (("L", lo), ("H", hi)):
        out.append(f"{name}{suffix}:")
        for i in range(0, N, 16):
            out.append("\t.byte " + ",".join(f"${b:02X}" for b in arr[i:i + 16]))
    return out


def main():
    sd = [round((1 - 2 ** (-m / 192)) * 65536) for m in range(N)]
    su = [min(65535, round((2 ** (m / 192) - 1) * 65536)) for m in range(N)]
    nd = [round(2 * (2 ** (m / 192) - 1) * 8192) for m in range(N)]
    nu = [round(2 * (1 - 2 ** (-m / 192)) * 8192) for m in range(N)]
    lines = ["; generated by tools/gen_bend.py - do not edit (193 entries: 0-12 semitones in 1/16)"]
    for name, vals in (("sidDn", sd), ("sidUp", su), ("nesDn", nd), ("nesUp", nu)):
        lines += tab(name, vals)
    # VINYL STOP: speed s = (256 - v) / 256 as vinylLvl v goes 0-255, the
    # pitch 12 log2(1/s) semitones down (like a record slowing). vinPitch: the
    # first octave (all chips, 0-192 sixteenths); vinSid: the SID's second
    # octave on top (0-192). vinStretch (every 4th v): step length x (1 + t/32)
    # = 1/s, up to 8x (v 224 on; at 248 it has stopped: silent).
    import math
    vp, vs = [], []
    for v in range(256):
        m = 192 * math.log2(256 / (256 - min(v, 192)))
        vp.append(min(192, round(m)))
        vs.append(max(0, min(192, round(m) - 192)))
    st = []
    for i in range(64):
        v = min(i * 4, 224)
        st.append(min(255, round((256 / (256 - v) - 1) * 32)))
    lines.append("vinPitch:")
    for i in range(0, 256, 16):
        lines.append("\t.byte " + ",".join(str(b) for b in vp[i:i + 16]))
    lines.append("vinSid:")
    for i in range(0, 256, 16):
        lines.append("\t.byte " + ",".join(str(b) for b in vs[i:i + 16]))
    lines.append("vinStretch:")
    for i in range(0, 64, 16):
        lines.append("\t.byte " + ",".join(str(b) for b in st[i:i + 16]))
    open(OUT, "w").write("\n".join(lines) + "\n")
    print("bendtab.asm written")


if __name__ == "__main__":
    main()
