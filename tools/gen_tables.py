#!/usr/bin/env python3
"""Generate src/tables.asm: SID frequency table (NTSC) for MIDI notes 0-127."""
import os

CLOCK = 1022727.14  # NTSC C64 CPU clock (Hz)
OUT = os.path.join(os.path.dirname(__file__), "..", "src", "tables.asm")


def main():
    lo, hi = [], []
    for n in range(128):
        f = 440.0 * 2 ** ((n - 69) / 12)
        v = min(0xFFFF, round(f * 16777216 / CLOCK))
        lo.append(v & 0xFF)
        hi.append(v >> 8)
    with open(OUT, "w") as fh:
        fh.write("; generated by tools/gen_tables.py - do not edit\n")
        fh.write("; SID frequency registers for MIDI notes 0-127 (NTSC clock)\n")
        for name, arr in (("sidFreqLo", lo), ("sidFreqHi", hi)):
            fh.write(f"{name}:\n")
            for i in range(0, 128, 16):
                fh.write("\t.byte " + ",".join(f"${b:02X}" for b in arr[i:i + 16]) + "\n")
    print("tables.asm written")


if __name__ == "__main__":
    main()

